import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseDocument } from "yaml";
import { isExcluded } from "./study-release.mjs";

// Build-time packaging only. Skills remain static instructions, with no runtime
// scripts or access to the repository filesystem from the MCP service.
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = resolve(root, "plugins/study/skills");
const destination = resolve(root, "apps/core/src/mcp/studySkillCatalog.generated.ts");
const names = ["canvas", "daily-brief", "study", "study-lecture"];
const catalog = { skills: [], resources: [] };

async function filesIn(directory, prefix = "") {
  const files = [];
  for (const entry of (await readdir(directory, { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name, "en"))) {
    assert(!entry.isSymbolicLink(), "Skill packages cannot contain symlinks");
    assert(/^[A-Za-z0-9._-]+$/.test(entry.name) && ![".", ".."].includes(entry.name), "Unsafe skill filename");
    const path = prefix + entry.name;
    assert(!isExcluded(path), `Forbidden Skill resource: ${path}`);
    if (entry.isDirectory()) files.push(...await filesIn(resolve(directory, entry.name), path + "/"));
    else {
      assert(entry.isFile(), "Only regular skill files are supported");
      files.push(path);
    }
  }
  return files;
}

for (const name of names) {
  const directory = resolve(source, name);
  const paths = await filesIn(directory);
  assert(paths.includes("SKILL.md") && paths.length <= 100, "Invalid skill file count");
  const manifest = [];
  let frontmatter;
  let totalBytes = 0;
  for (const path of paths) {
    const bytes = await readFile(resolve(directory, path));
    const uri = `skill://hanyang-study/${name}/${path}`;
    const textual = /\.(md|ya?ml|json|txt|csv|tsv|html|css|js|mjs|ts|svg)$/i.test(path);
    const resource = textual
      ? { uri, mimeType: path.endsWith(".md") ? "text/markdown" : path.endsWith(".yaml") || path.endsWith(".yml") ? "application/yaml" : "text/plain", text: new TextDecoder("utf-8", { fatal: true }).decode(bytes).replaceAll("\r\n", "\n") }
      : { uri, mimeType: "application/octet-stream", blob: bytes.toString("base64") };
    const payload = "text" in resource ? Buffer.from(resource.text, "utf8") : bytes;
    assert(payload.length <= (path === "SKILL.md" ? 256 * 1024 : 1024 * 1024), "Skill file exceeds import limit");
    totalBytes += payload.length;
    manifest.push({ uri, digest: `sha256:${createHash("sha256").update(payload).digest("hex")}` });
    catalog.resources.push(resource);
    if (path === "SKILL.md") {
      const header = resource.text.match(/^---\n([\s\S]*?)\n---(?:\n|$)/);
      assert(header, "Missing skill frontmatter");
      const document = parseDocument(header[1], { uniqueKeys: true });
      assert.equal(document.errors.length, 0, `Invalid frontmatter: ${name}`);
      frontmatter = document.toJS();
      assert(frontmatter && typeof frontmatter === "object" && !Array.isArray(frontmatter));
      assert.equal(frontmatter.name, name);
      assert.equal(typeof frontmatter.description, "string");
    }
  }
  assert(totalBytes <= 5 * 1024 * 1024, "Skill exceeds import size limit");
  catalog.skills.push({ uri: `skill://hanyang-study/${name}/SKILL.md`, frontmatter, resources: manifest });
}

const generated = '// Generated by scripts/build-mcp-skills.mjs. Do not edit.\n'
  + '// Text files use LF, matching repository .gitattributes.\n'
  + 'import type { StaticSkillCatalog } from "./staticSkills.js";\n\n'
  + `export const studySkillCatalog = ${JSON.stringify(catalog, null, 2)} as const satisfies StaticSkillCatalog;\n`;
if (process.argv.includes("--check")) {
  assert.equal(await readFile(destination, "utf8"), generated, "MCP Skills snapshot is stale; run npm run build:mcp-skills");
  console.log(`MCP snapshot matches ${catalog.skills.length} skills and ${catalog.resources.length} files.`);
} else {
  await writeFile(destination, generated, "utf8");
  console.log(`Packaged ${catalog.skills.length} static MCP skills and ${catalog.resources.length} files.`);
}
